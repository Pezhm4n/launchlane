import { ensure } from "../errors.ts";
import { exactKeys, object, string } from "../../contracts/validation.ts";

const pythonKeywords = new Set("False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield".split(" "));
const identifier = (value: string) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(value) && !pythonKeywords.has(value);

/** Generate only; the caller owns conflict checks, artifact provenance and sandbox execution. */
export function compositeBootstrapSource(value: unknown): string {
  const input = object(value);
  exactKeys(input, ["module", "exportName", "publicDirectory"]);
  const module = string(input.module, 200), exportName = string(input.exportName, 64);
  const publicDirectory = input.publicDirectory === undefined ? "launchlane-public" : string(input.publicDirectory, 160);
  ensure(module.split(".").every(identifier) && module !== "launchlane_entry" && !module.startsWith("launchlane_entry.") && identifier(exportName),
    "COMPOSITE_ENTRY_INVALID", "نام ماژول و برنامهٔ Python باید مشخص و معتبر باشد.");
  ensure(publicDirectory.split("/").every(part => /^[A-Za-z0-9][A-Za-z0-9_-]*$/.test(part) &&
    !["src", "source", "node_modules", "api", "tests"].includes(part.toLowerCase())),
    "COMPOSITE_PUBLIC_PATH_INVALID", "مسیر فایل‌های ساخته‌شده باید پوشه‌ای مشخص و نسبی باشد.");
  return `# Generated by Launchlane; application source remains unchanged.
import importlib
from pathlib import Path
from starlette.applications import Starlette
from starlette.responses import JSONResponse
from starlette.routing import Match
from starlette.staticfiles import StaticFiles
import uvicorn

_root = Path(__file__).resolve().parent
_public = (_root / ${JSON.stringify(publicDirectory)}).resolve()
_unresolved_public = _root / ${JSON.stringify(publicDirectory)}
if (any(path.is_symlink() for path in (_unresolved_public, *_unresolved_public.parents) if path.is_relative_to(_root) and path != _root)
        or not _public.is_relative_to(_root) or _public == _root or not (_public / 'index.html').is_file()):
    raise RuntimeError('Launchlane compiled frontend is missing or outside the artifact')
app = getattr(importlib.import_module(${JSON.stringify(module)}), ${JSON.stringify(exportName)})
if not isinstance(app, Starlette):
    raise RuntimeError('Launchlane composite entry requires a FastAPI or Starlette application')
_original_routes = tuple(app.routes)
if any(getattr(route, 'path', None) in ('', '/') for route in _original_routes):
    raise RuntimeError('Launchlane frontend conflicts with an existing root route or mount')

class _LaunchlaneStatic(StaticFiles):
    async def __call__(self, scope, receive, send):
        path = self.get_path(scope)
        parts = path.strip('/').split('/')
        if parts[0] == 'api':
            # Preserve method errors from original API routes; unknown APIs never serve HTML.
            for route in _original_routes:
                match, _ = route.matches(scope)
                if match == Match.PARTIAL:
                    await route.handle(scope, receive, send)
                    return
            await JSONResponse({'detail': 'Not Found'}, status_code=404)(scope, receive, send)
            return
        raw_parts = scope.get('path', '').split('/')
        forbidden = {'src', 'source', 'node_modules', '__pycache__', 'tests'}
        suffixes = {'.html', '.htm', '.js', '.mjs', '.css', '.svg', '.png', '.jpg', '.jpeg', '.gif', '.webp', '.avif', '.ico', '.woff', '.woff2', '.ttf', '.otf', '.eot', '.wasm', '.webmanifest', '.json', '.xml'}
        if (any(part.startswith('.') or part.lower() in forbidden for part in raw_parts if part)
                or (Path(path).suffix.lower() not in suffixes and path not in ('.', '', 'robots.txt'))):
            await JSONResponse({'detail': 'Not Found'}, status_code=404)(scope, receive, send)
            return
        await super().__call__(scope, receive, send)

# Appending retains existing API routes, error handlers and lifespan behavior.
app.mount('/', _LaunchlaneStatic(directory=str(_public), html=True, follow_symlink=False), name='launchlane-web')
if __name__ == '__main__':
    uvicorn.run(app, host='0.0.0.0', port=8000, access_log=False)
`;
}
